def read_defines(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = text.replace("\\\n", " ")
    out = []
    for line in text.split("\n"):
        line = line.strip()
        if not line.startswith("#define"):
            continue
        m = re.match(r"#define\s+(\w+)(\([^)]*\))?\s*(.*)$", line)
        if not m:
            continue
        name, args, body = m.group(1), m.group(2) or "", m.group(3).strip()
        out.append((name, args, body))
    return out


def main():
    files = ["reg.h", "phy.h", "ar9002_phy.h", "mac.h"]
    seen = {}
    order = []
    for f in files:
        for name, args, body in read_defines(os.path.join(LINUX, f)):
            if name.startswith("AR_SREV_") and args:
                continue
            if name in ("ds_ctl2", "ds_ctl3") or "->" in body or "u." in body:
                continue
            if "struct" in body or "sizeof" in body or "ah->" in body:
                continue
            if name in seen:
                continue
            seen[name] = (args, body)
            order.append(name)

    referenced = set()
    for name in order:
        args, body = seen[name]
        for m in re.finditer(r"AR_SREV_\w+", body):
            referenced.add(m.group(0))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "ath9k_regs.h"), "w") as fh:
        fh.write(BANNER)
        fh.write("#pragma once\n\n#include <stdint.h>\n\n")
        fh.write("#ifndef BIT\n#define BIT(n) (1U << (n))\n#endif\n")
        fh.write("#ifndef ATH9K_REGS_COMPAT\n#define ATH9K_REGS_COMPAT\n")
        fh.write("#define MS(_v, _f) (((_v) & _f) >> _f##_S)\n")
        fh.write("#define SM(_v, _f) (((_v) << _f##_S) & _f)\n")
        fh.write("#endif\n\n")
        for sr in sorted(referenced):
            fh.write("#define %s(_ah) %d\n" % (sr, 1 if sr in SREV_TRUE else 0))
        fh.write("\n")
        for name in order:
            args, body = seen[name]
            if name in ("MS", "SM", "BIT"):
                continue
            fh.write("#ifndef %s\n#define %s%s %s\n#endif\n" % (name, name, args, body))
    print("wrote", os.path.join(OUT, "ath9k_regs.h"), len(order), "defines")

    src = open(os.path.join(LINUX, "ar9002_initvals.h"), encoding="utf-8", errors="replace").read()
    wanted = [
        "ar9285Modes_9285_1_2", "ar9285Common_9285_1_2",
        "ar9285Modes_high_power_tx_gain_9285_1_2",
        "ar9285Modes_original_tx_gain_9285_1_2",
        "ar9285Modes_XE2_0_normal_power", "ar9285Modes_XE2_0_high_power",
        "ar9280PciePhy_clkreq_always_on_L1_9280",
    ]
    with open(os.path.join(OUT, "ath9k_initvals.h"), "w") as fh:
        fh.write(BANNER)
        fh.write("#pragma once\n\n#include <stdint.h>\n\n")
        for name in wanted:
            m = re.search(r"static const u32 %s\[\]\[(\d)\] = \{(.*?)\n\};" % name, src, re.S)
            if not m:
                sys.exit("missing " + name)
            cols = int(m.group(1))
            body = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
            body = re.sub(r"//[^\n]*", "", body)
            rows = re.findall(r"\{([^{}]*)\}", body)
            fh.write("static const uint32_t %s[][%d] = {\n" % (name, cols))
            for r in rows:
                vals = [v.strip() for v in r.split(",") if v.strip()]
                if len(vals) != cols:
                    sys.exit("bad row in %s: %r" % (name, r))
                fh.write("    {%s},\n" % ", ".join(vals))
            fh.write("};\n#define %s_ROWS (sizeof(%s) / sizeof(%s[0]))\n\n" % (name.upper(), name, name))
    print("wrote initvals")


if __name__ == "__main__":
    main()
