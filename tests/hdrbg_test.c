int main(void) {
  uint8_t entropy[64];
  uint8_t reseed[64];
  for (int i = 0; i < 64; i++) {
    entropy[i] = (uint8_t)i;
    reseed[i] = (uint8_t)(64 + i);
  }
  struct hdrbg state;
  uint8_t out[200];
  hdrbg_instantiate(&state, entropy, sizeof(entropy), (const uint8_t *)"test", 4);
  assert(hdrbg_generate(&state, out, 100) == 0);
  assert(memcmp(out, expect_a, 100) == 0);
  assert(hdrbg_generate(&state, out, 200) == 0);
  assert(memcmp(out, expect_b, 200) == 0);
  hdrbg_reseed(&state, reseed, sizeof(reseed), (const uint8_t *)"x", 1);
  assert(hdrbg_generate(&state, out, 64) == 0);
  assert(memcmp(out, expect_c, 64) == 0);
  assert(hdrbg_generate(&state, out, HDRBG_MAX_REQUEST + 1) == -1);
  struct hdrbg fresh;
  memset(&fresh, 0, sizeof(fresh));
  assert(hdrbg_generate(&fresh, out, 8) == -1);
  return 0;
}
