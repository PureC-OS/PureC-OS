static inline uint8_t gfx_font_row(gfx_font_face_t face, uint8_t ch,
                                   uint32_t row) {
    if (face == GFX_FONT_BOLD) {
        uint8_t bits = GFX_FONT[ch][row & 7];
        return (uint8_t)(bits | (bits >> 1));
    }
    if (face == GFX_FONT_CLEAN) {
        if (row >= 7) return 0;
        return (uint8_t)(GFX_FONT_CLEAN_BITS[ch][row] << 2);
    }
    return GFX_FONT[ch][row & 7];
}

static inline uint32_t gfx_text_width(const char *text, uint32_t size) {
    uint32_t n = 0;
    if (!text) return 0;
    while (text[n]) n++;
    if (size < 8) size = 8;
    if (size > 48) size = 48;
    return n * size;
}

static inline void gfx_draw_char(char c, uint32_t x, uint32_t y,
                                 uint32_t fg, uint32_t size,
                                 gfx_font_face_t face, gfx_rect_fn rect,
                                 void *ctx) {
    if (!rect) return;
    if ((uint8_t)c >= 128) return;
    if (size < 8) size = 8;
    if (size > 48) size = 48;
    uint8_t ch = (uint8_t)c;
    for (uint32_t r = 0; r < 8; r++) {
        uint8_t bits = gfx_font_row(face, ch, r);
        if (!bits) continue;
        uint32_t y0 = y + (r * size) / 8;
        uint32_t y1 = y + ((r + 1) * size) / 8;
        if (y1 <= y0) continue;
        uint32_t run_start = 0;
        bool in_run = false;
        for (uint32_t col = 0; col <= 8; col++) {
            bool set = col < 8 && (bits & (1u << (7 - col)));
            if (set && !in_run) { run_start = col; in_run = true; }
            if ((!set || col == 8) && in_run) {
                uint32_t x0 = x + (run_start * size) / 8;
                uint32_t x1 = x + (col * size) / 8;
                if (x1 > x0)
                    rect(x0, y0, x1 - x0, y1 - y0, fg, ctx);
                in_run = false;
            }
        }
    }
}

static inline void gfx_draw_text(const char *text, uint32_t x, uint32_t y,
                                 uint32_t fg, uint32_t size,
                                 gfx_font_face_t face, gfx_rect_fn rect,
                                 void *ctx) {
    if (!text || !rect) return;
    if (size < 8) size = 8;
    if (size > 48) size = 48;
    while (*text) {
        gfx_draw_char(*text, x, y, fg, size, face, rect, ctx);
        x += size;
        text++;
    }
}

