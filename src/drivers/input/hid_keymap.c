uint8_t hid_modifier_bit(uint16_t scancode){
    if(scancode < HID_KEY_LCTRL || scancode > HID_KEY_RGUI) return 0;
    static const uint8_t bits[8] = {
        KEY_MOD_LCTRL, KEY_MOD_LSHIFT, KEY_MOD_LALT, KEY_MOD_LGUI,
        KEY_MOD_RCTRL, KEY_MOD_RSHIFT, KEY_MOD_RALT, KEY_MOD_RGUI
    };
    return bits[scancode - HID_KEY_LCTRL];
}
